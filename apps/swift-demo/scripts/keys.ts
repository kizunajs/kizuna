import { mkdirSync, writeFileSync } from 'node:fs';
import { FRACTIONAL_KEY_SWIFT } from '../../../packages/swift/src/fractional-key.js';

/**
 * Writes the `FractionalKey` the Swift generator emits into a target of its
 * own, so the tests check it against the shared vectors without an API that
 * holds a key.
 */
mkdirSync('swift/Sources/FractionalKey', {
    recursive: true,
});
writeFileSync(
    'swift/Sources/FractionalKey/FractionalKey.swift',
    `// Generated by @kizunajs/swift. Do not edit.\n// Regenerate: pnpm --filter @kizunajs-demo/swift generate\n\n${FRACTIONAL_KEY_SWIFT}`
);
