import { mkdirSync, writeFileSync } from 'node:fs';
import { FRACTIONAL_KEY_KOTLIN } from '../../../packages/kotlin/src/fractional-key.js';

/**
 * Writes the `FractionalKey` the Kotlin generator emits into a package of its
 * own, so the tests check it against the shared vectors without an API that
 * holds a key.
 */
mkdirSync('kotlin/src/main/kotlin/com/kizuna/demo/keys', {
    recursive: true,
});
writeFileSync(
    'kotlin/src/main/kotlin/com/kizuna/demo/keys/FractionalKey.kt',
    `// Generated by @kizunajs/kotlin. Do not edit by hand.\n// Regenerate: pnpm --filter @kizunajs-demo/kotlin generate\n\npackage com.kizuna.demo.keys\n\n${FRACTIONAL_KEY_KOTLIN}`
);
